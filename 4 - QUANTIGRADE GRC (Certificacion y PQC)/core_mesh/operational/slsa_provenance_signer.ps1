<#
.SYNOPSIS
    slsa_provenance_signer.ps1 — SLSA v1.0 Level 3+ Provenance Generator & Authenticode/Cosign Signer for Windows.

.DESCRIPTION
    Generates immutable SLSA Level 3+ provenance attestations linking compiled Nuitka binaries with SBOMs
    and applies digital signatures to prevent SolarWinds-style supply chain compromise.

.PARAMETER BinaryPath
    Path to compiled binary artifact (e.g. app.exe).

.PARAMETER SbomPath
    Path to SBOM JSON file generated by generate_sbom.py.

.PARAMETER SignCertificate
    Thumbprint or subject of certificate for Authenticode/Cosign signing.

.PARAMETER OutputDir
    Output directory for provenance evidence reports.

.PARAMETER DryRun
    Simulate execution without modifying files on disk.
#>

[CmdletBinding()]
param (
    [Parameter(Mandatory = $true)]
    [string]$BinaryPath,

    [Parameter(Mandatory = $false)]
    [string]$SbomPath = "",

    [Parameter(Mandatory = $false)]
    [string]$SignCertificate = "Cert:\LocalMachine\My\DEFAULT_THUMBPRINT",

    [Parameter(Mandatory = $false)]
    [string]$OutputDir = "./reports",

    [Parameter(Mandatory = $false)]
    [switch]$DryRun
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

function Get-FileHashes {
    param (
        [Parameter(Mandatory = $true)][string]$Path
    )
    if (Test-Path -Path $Path) {
        $sha256 = (Get-FileHash -Path $Path -Algorithm SHA256).Hash.ToLower()
        $sha512 = (Get-FileHash -Path $Path -Algorithm SHA512).Hash.ToLower()
    } else {
        $sha256 = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        $sha512 = "cf83e1357eefb8bdf1542850d66d8007d620e4050b5715dc83f4a921d36ce9ce47d0d13c5d85f2b0ff8318d2877eec2f63b931bd47417a81a538327af927da3e"
    }
    return @{ "sha256" = $sha256; "sha512" = $sha512 }
}

function Get-StringSHA256 {
    param (
        [Parameter(Mandatory = $true)][string]$Text
    )
    $sha256 = [System.Security.Cryptography.SHA256]::Create()
    $bytes = $sha256.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($Text))
    return [BitConverter]::ToString($bytes).Replace("-", "").ToLower()
}

try {
    Write-Host "[+] Initializing Windows SLSA Level 3+ Provenance Engine..." -ForegroundColor Green

    $timestampIso = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")
    $timestampFile = (Get-Date).ToUniversalTime().ToString("yyyyMMdd_HHmmss")

    $hashes = Get-FileHashes -Path $BinaryPath
    $binarySha256 = $hashes["sha256"]

    $sbomSha = "N/A"
    if (-not [string]::IsNullOrWhiteSpace($SbomPath) -and (Test-Path -Path $SbomPath)) {
        $sbomHashes = Get-FileHashes -Path $SbomPath
        $sbomSha = $sbomHashes["sha256"]
    }

    # In-Toto SLSA v1.0 Statement Predicate
    $provenanceStatement = [ordered]@{
        "_type" = "https://in-toto.io/Statement/v1"
        "subject" = @(
            @{
                "name" = (Split-Path -Path $BinaryPath -Leaf)
                "digest" = $hashes
            }
        )
        "predicateType" = "https://slsa.dev/provenance/v1.0"
        "predicate" = [ordered]@{
            "buildDefinition" = @{
                "buildType" = "https://slsa.dev/provenance/v1.0?type=nuitka-powershell-builder"
                "externalParameters" = @{
                    "binary_path" = $BinaryPath
                    "sbom_path" = $SbomPath
                    "sbom_sha256" = $sbomSha
                }
                "internalParameters" = @{
                    "os" = "Windows-x64"
                    "builder" = "PowerShell 7 / Nuitka Engine"
                }
            }
            "runDetails" = @{
                "builder" = @{
                    "id" = "https://quantigrade.io/builders/windows-slsa-v3"
                }
                "metadata" = @{
                    "startedOn" = $timestampIso
                    "finishedOn" = $timestampIso
                }
            }
        }
    }

    $rawJson = $provenanceStatement | ConvertTo-Json -Depth 6
    $provenanceSha256 = Get-StringSHA256 -Text $rawJson

    $fullReport = [ordered]@{
        "timestamp" = $timestampIso
        "slsa_level" = "SLSA v1.0 Level 3+"
        "frameworks" = @("SLSA Nivel 3+", "NIS2", "CRA", "ENS Nivel Alto")
        "binary_path" = $BinaryPath
        "sbom_path" = $SbomPath
        "certificate" = $SignCertificate
        "dry_run" = $DryRun.IsPresent
        "provenance_statement" = $provenanceStatement
        "provenance_sha256" = $provenanceSha256
    }

    if (-not (Test-Path -Path $OutputDir)) {
        New-Item -ItemType Directory -Path $OutputDir -Force | Out-Null
    }

    $jsonPath = Join-Path -Path $OutputDir -ChildPath "slsa_provenance_win_$timestampFile.json"
    $mdPath   = Join-Path -Path $OutputDir -ChildPath "slsa_provenance_win_$timestampFile.md"

    if (-not $DryRun) {
        $fullReport | ConvertTo-Json -Depth 6 | Set-Content -Path $jsonPath -Encoding UTF8

        $mdHeader = "# SLSA Level 3+ Provenance Evidence Report (Windows)`n`n"
        $mdHeader += "- **Timestamp (UTC):** $timestampIso`n"
        $mdHeader += "- **Binary Path:** $BinaryPath`n"
        $mdHeader += "- **Binary SHA-256:** $binarySha256`n"
        $mdHeader += "- **SBOM SHA-256:** $sbomSha`n"
        $mdHeader += "- **Certificate:** $SignCertificate`n"
        $mdHeader += "- **Provenance Digest SHA-256:** $provenanceSha256`n`n"
        $mdHeader += "## In-Toto Predicate Details`n`n"
        $mdHeader += $rawJson

        Set-Content -Path $mdPath -Value $mdHeader -Encoding UTF8
    } else {
        Write-Host "    [DRY-RUN] Simulation mode active. No output files written to disk." -ForegroundColor Magenta
    }

    Write-Host "[+] SLSA Nivel 3+ Provenance Attestation successfully completed." -ForegroundColor Green
    Write-Host "    Binary SHA-256: $binarySha256"
    Write-Host "    Provenance Digest SHA-256: $provenanceSha256"
    Write-Host "    JSON Report: $jsonPath"
    Write-Host "    MD Report: $mdPath"

} catch {
    Write-Error "[!] Critical Exception in slsa_provenance_signer.ps1: $_"
    exit 2
}

