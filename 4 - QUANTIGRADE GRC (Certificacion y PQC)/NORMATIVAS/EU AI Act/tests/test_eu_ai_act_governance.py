def test_eu_ai_act_art50_watermarking():
    """Verify EU AI Act Art. 50 zero-width watermark injection and detection."""
    watermarker = EUAIActModelWatermarker(watermark_secret="TEST_SECRET_KEY")
    synthetic_prompt_output = "This is a synthetic legal document generated by a compliant LLM."

    res = watermarker.inject_watermark(synthetic_prompt_output)
    watermarked_text = res["watermarked_text"]
    assert watermarked_text != synthetic_prompt_output
    assert len(watermarked_text) > len(synthetic_prompt_output)

    # Verification using actual method extract_and_verify_watermark
    is_valid, msg = watermarker.extract_and_verify_watermark(watermarked_text)
    assert is_valid is True
    assert "WATERMARK_AUTHENTIC" in msg


def test_ai_model_provenance_signer(tmp_path: Path):
    """Verify cryptographic signing and provenance validation of AI model weights/manifest."""
    model_file = tmp_path / "model_weights.bin"
    model_file.write_bytes(b"dummy_weights_tensor_data_v1.0")

    signer = AIModelProvenanceSigner(
        model_path=str(model_file),
        secret_key="TEST_PROVENANCE_KEY",
    )
    manifest = signer.sign_model_provenance()
    assert manifest["model_name"] == "model_weights.bin"
    assert "sha256" in manifest["digests"]
    assert "signature_hmac_sha256" in manifest

    # Verification using actual method verify_model_provenance
    is_valid, _ = signer.verify_model_provenance()
    assert is_valid is True

    # Tamper test
    model_file.write_bytes(b"tampered_weights!")
    is_valid_tampered, _ = signer.verify_model_provenance()
    assert is_valid_tampered is False


